import json
import re
from collections.abc import Sequence
from typing import Protocol

from dotenv import load_dotenv
from pydantic import BaseModel, Field

from config.local_ai import create_chat_model, get_embeddings, get_vector_store
from vectorstore.chroma_store import Retriever as ChromaRetriever

load_dotenv()

class RetrievedDocument(Protocol):
    page_content: str


class ContextRetriever(Protocol):
    def retrieve(
        self,
        query: str,
        company: str,
        year: int | None = None,
        k: int = 4
    ) -> Sequence[RetrievedDocument]: ...


class FinancialMetrics(BaseModel):
    revenue: str | int | None = Field(None, alias="Revenue")
    net_income: str | int | None = Field(None, alias="Net Income")
    operating_income: str | int | None = Field(None, alias="Operating Income")
    cash_flow: str | int | None = Field(None, alias="Cash Flow from Operating Activities")
    total_assets: str | int | None = Field(None, alias="Total Assets")
    total_liabilities: str | int | None = Field(None, alias="Total Liabilities")
    risk_factors: str | list | None = Field(None, alias="Top Risk Factors")
    growth_drivers: str | list | None = Field(None, alias="Top Growth Drivers")


def retrieve_context(
    retriever: ContextRetriever,
    company: str,
    year: int | None
) -> str:
    """
    Retrieve broad financial context from ChromaDB.
    """
    query = f"""
    Annual report financial statements,
    income statement,
    balance sheet,
    cash flow statement,
    risks,
    growth drivers,
    financial performance
    for {company} fiscal year {year or "not specified"}
    """

    # Retrieve matching LangChain Document objects from ChromaDB
    documents = retriever.retrieve(
        query=query,
        company=company,
        year=year,
        k=20
    )

    return "\n\n".join(
        doc.page_content
        for doc in documents
    )


def build_extraction_prompt(
    company: str,
    year: int | None,
    context: str
) -> str:
    """
    Build KPI extraction prompt.
    """
    return f"""
You are an expert financial analyst.

Company: {company}
Year: {year or "not specified"}

Context:
{context}

Extract the following information:

1. Revenue
2. Net Income
3. Operating Income
4. Cash Flow from Operating Activities
5. Total Assets
6. Total Liabilities
7. Top Risk Factors
8. Top Growth Drivers

Instructions:

- Use only the provided context.
- Return null if unavailable.
- Leave the six numeric financial fields null; those values are read directly
  from the report tables.
- Risk factors should be concise.
- Growth drivers should be concise.
- Return valid JSON only.
"""


def extract_statement_metrics(report_text: str) -> dict[str, str | None]:
    """Read financial values from matching statement rows in extracted report text."""
    row_labels = {
        "revenue": "total net sales",
        "net_income": "net income",
        "operating_income": "operating income",
        "cash_flow": "cash generated by operating activities",
        "total_assets": "total assets",
        "total_liabilities": "total liabilities",
    }
    values: dict[str, str | None] = {key: None for key in row_labels}

    for line in report_text.splitlines():
        cells = line.strip().split("|")
        if len(cells) < 3:
            continue

        label = cells[1].strip().casefold()
        for field, row_label in row_labels.items():
            value = cells[2].strip()
            if (
                values[field] is None
                and label == row_label
                and value
                and re.search(r"\d", value)
            ):
                values[field] = value

    return values


def extract_financial_metrics(
    retriever: ContextRetriever,
    company: str,
    year: int | None,
    report_text: str | None = None
) -> dict:
    """
    Extract KPIs using RAG.
    """
    context = retrieve_context(
        retriever=retriever,
        company=company,
        year=year
    )

    prompt = build_extraction_prompt(
        company=company,
        year=year,
        context=context
    )

    schema = FinancialMetrics.model_json_schema()
    structured_prompt = (
        f"{prompt}\nJSON schema:\n{json.dumps(schema)}\n"
        "Return one JSON object matching this schema and no other text."
    )
    response = create_chat_model(format="json").invoke(structured_prompt)
    if not isinstance(response.content, str):
        raise TypeError("Ollama returned a non-text response for KPI extraction.")
    metrics = FinancialMetrics.model_validate_json(response.content).model_dump()
    metrics.update(extract_statement_metrics(report_text or context))

    return metrics


def main() -> None:
    company = "Apple"
    year = 2024

    embeddings = get_embeddings()
    vector_store_wrapper = get_vector_store()

    # 3. Access underlying LangChain Chroma instance bound with embeddings
    chroma_instance = vector_store_wrapper.get_store(embeddings)

    # 4. Initialize local Chroma Retriever wrapper
    retriever = ChromaRetriever(chroma_instance)

    # 5. Extract metrics using RAG
    results = extract_financial_metrics(
        retriever=retriever,
        company=company,
        year=year
    )

    print(f"\nExtracted KPIs for {company} {year}\n")

    for key, value in results.items():
        print(f"{key}:")
        print(value)
        print("-" * 80)

    # 6. Save extracted metrics to database
    from database.save_metrics import save_metrics

    save_metrics(
        company=company,
        year=year,
        metrics=results
    )


if __name__ == "__main__":
    main()